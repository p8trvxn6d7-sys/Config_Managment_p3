# Тестовая программа этапа 4: команда abs() с сохранением результата в память
# Исходные значения: адреса 30..34, результаты abs(): адреса 40..44

# Отрицательное число: abs(-17) = 17
r1 = -17
mem[30] = r1
r2 = 40
mem[r2] = abs(r1)

# Положительное число не меняется: abs(25) = 25
r1 = 25
mem[31] = r1
r2 = 41
mem[r2] = abs(r1)

# Ноль: abs(0) = 0
r1 = 0
mem[32] = r1
r2 = 42
mem[r2] = abs(r1)

# Наименьшая константа: abs(-1073741824) = 1073741824
r1 = -1073741824
mem[33] = r1
r2 = 43
mem[r2] = abs(r1)

# Наибольшая константа: abs(1073741823) = 1073741823
r1 = 1073741823
mem[34] = r1
r2 = 44
